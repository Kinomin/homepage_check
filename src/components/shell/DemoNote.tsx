import { IS_STATIC_DEMO } from '@/lib/static-demo';

/**
 * デモデータで動作していることの明示。
 * 架空のサンプルを分析結果として提示させないため、必ず画面上部に出す。
 *
 * 理由を断定しない。接続していないのか、まだ走査していないのかは
 * この画面からは区別できないため、両方あることを示す
 * （走査失敗と「情報がない」を混ぜない、という原則と同じ考え方）。
 *
 * 静的デモ（GitHub Pages）では原因が確定しているので、そちらを書く。
 */
export function DemoNote({ isDemo }: { isDemo: boolean }) {
  if (!isDemo) return null;

  if (IS_STATIC_DEMO) {
    return (
      <div className="demo-note">
        <b>公開デモ</b>
        ｜画面と操作を確認するためのページです。学校名・数値・判定結果はすべて架空で、実在の学校のものではありません。
        サーバを持たないため、ログイン・サイトの走査・LLMによる判定は動きません（
        <b>02 欠落マップの根拠パネル・06 のグループ化・07 のA4横1枚出力</b>
        などは動きます）。
      </div>
    );
  }

  return (
    <div className="demo-note">
      プロトタイプ由来のサンプルデータを表示しています。学校名・数値・判定結果はすべて架空です。
      実際の結果を出すには、Supabase への接続と、1回以上の走査が必要です。
    </div>
  );
}
